export function formatPKR(amount) {
  if (!amount || amount === 0) return "See details";
  if (amount >= 100000) return `PKR ${(amount / 1000).toFixed(0)}k / sem`;
  return `PKR ${amount.toLocaleString("en-PK")} / sem`;
}

const CITY_PROVINCE = {
  Lahore: "Punjab",
  Faisalabad: "Punjab",
  "Kala Shah Kaku": "Punjab",
  Islamabad: "Islamabad Capital Territory",
  Karachi: "Sindh",
};

function admissionDatesFor(c) {
  if (c.admission_open != null || c.admission_close != null) {
    return {
      admission_open: c.admission_open || null,
      admission_close: c.admission_close || null,
    };
  }
  if (c.admissionStatus === "open") {
    return { admission_open: "2026-07-01", admission_close: "2026-09-18" };
  }
  if (c.admissionStatus === "closed") {
    return { admission_open: "2026-06-01", admission_close: "2026-08-20" };
  }
  return { admission_open: null, admission_close: null };
}

export function normalizeCampus(c) {
  const dates = admissionDatesFor(c);
  const fee = c.feePerSemester || 0;
  return {
    ...c,
    id: c.id,
    name: c.campusName || c.name,
    city: c.city,
    province: c.province || CITY_PROVINCE[c.city] || "",
    students: c.students || null,
    fee_min: c.fee_min ?? (fee ? Math.round(fee * 0.85) : null),
    fee_max: c.fee_max ?? (fee || null),
    fee_period: c.fee_period || "sem",
    _mainFlag: c.isMain === true || c.campusCategory === "Main Campus",
    admission_open: dates.admission_open,
    admission_close: dates.admission_close,
    cover_image: c.coverImage || c.cover_image || null,
  };
}

/** Only the first flagged campus in a list keeps the main-campus badge. */
export function enforceSingleMainCampus(list) {
  let found = false;
  return list.map((c) => {
    if (c._mainFlag && !found) {
      found = true;
      return { ...c, is_main: true };
    }
    return { ...c, is_main: false };
  });
}

export function getCampusesForUniversity(universityId) {
  const filtered = campuses
    .filter((c) => c.universityId === universityId)
    .map(normalizeCampus);
  return enforceSingleMainCampus(filtered);
}

export function getCampusById(id) {
  const raw = campuses.find((c) => String(c.id) === String(id));
  if (!raw) return null;
  const [normalised] = enforceSingleMainCampus([normalizeCampus(raw)]);
  return normalised;
}
